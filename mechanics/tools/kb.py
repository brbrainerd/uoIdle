#!/usr/bin/env python3
"""UO Idle mechanics knowledge base tool: build INDEX.md, lint pages & raw manifest, scan credentials, self-test.

Examples:
  python3 mechanics/tools/kb.py build --root mechanics
  python3 mechanics/tools/kb.py check --root mechanics
  python3 mechanics/tools/kb.py --self-test

A page is mechanics/<dir>/<slug>.md across PAGE_DIRS (classes, combat, systems,
topics, entities, modernuo). Its frontmatter is the nine FM_KEYS in order, one
`key: <JSON literal>` per line between two `---` lines: valid YAML flow syntax,
parsed with json.loads per value so no third-party YAML library is needed.
`build` writes INDEX.md from the pages; `check` fails on any schema defect,
stale INDEX, manifest mismatch, or leaked credential/session token. A claim
cites `(raw L<a>-L<b>)` of sources[0], or, on a topics page only, `(evidence N)`:
the Nth `evidence` entry. A `[[slug]] C<n>` reference must name a claim that
page has. Every mode prints one JSON object and exits 0 only when `"ok": true`.

Stdlib only; runs under Python 3.9+ (macOS /usr/bin/python3 and Homebrew python3).
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import shutil
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Callable, Dict, List, Optional, Tuple

FM_KEYS = ("id", "title", "category", "aliases", "status", "sources", "evidence", "code_refs", "updated")
LIST_KEYS = ("aliases", "sources", "evidence", "code_refs")
TAGS = ("contradicted", "unverified", "modernuo-stated", "doc-stated", "bundle-stated", "verified")
RANK = {
    "contradicted": 0,
    "unverified": 1,
    "modernuo-stated": 2,
    "doc-stated": 3,
    "bundle-stated": 4,
    "verified": 5,
}  # weakest first
RAW_ONLY_TAGS = ("modernuo-stated", "doc-stated", "bundle-stated")
CATEGORIES = (
    "classes",
    "skills",
    "combat",
    "status-effects",
    "progression",
    "items-equipment",
    "dungeons-monsters",
    "crafting-gathering",
    "companions-mounts",
    "engine-ui",
    "modernuo-bushido",
    "modernuo-ninjitsu",
)
PAGE_DIRS = ("classes", "combat", "systems", "topics", "entities", "modernuo")
RAW_DIR = "_raw"
MANIFEST_NAME = "manifest.json"
RAW_SUBDIRS = ("bundle", "api", "wiki", "modernuo")

FM_LINE = re.compile(r"^([a-z_]+): (.+)$")
DATE_RE = re.compile(r"^\d{4}-\d{2}-\d{2}$")
SLUG_RE = re.compile(r"^[a-z0-9][a-z0-9-]*$")
RAW_FILENAME_RE = re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]*$")
HEX64 = re.compile(r"^[0-9a-f]{64}$")
WIKI_LINK = re.compile(r"\[\[([^\]]*)\]\]")
MD_LINK = re.compile(r"\]\(([^)\s]+)\)")
# Greedy quote so embedded double quotes survive.
# Groups: 1 id, 2 tag, 3 quote, 4-5 raw lines, or 6 the 1-based `evidence` index
# of a topics-page claim.
CLAIM_LINE = re.compile(r'^- \*\*C(\d+)\*\* \[([a-z-]+)\] "(.*)" \((?:raw L(\d+)(?:-L(\d+))?|evidence (\d+))\)$')
CLAIM_PREFIX = "- **C"
CLAIM_REF = re.compile(r"\[\[([^\]]*)\]\] C(\d+)(?!\d)")  # `[[slug]] C<n>` names claim n of that page
EVIDENCE_PREFIXES = ("bundle: ", "network: ", "dom: ", "wiki: ", "modernuo: ", "sim: ", "code: ", "live: ")
MEASURED_PREFIXES = ("network: ", "dom: ", "sim: ", "live: ")  # what a verified or contradicted evidence claim needs
# `live: _evidence/<file> L<a>[-L<b>]`: lines of a committed, redacted runtime/session excerpt.
LIVE_CITE = re.compile(r"^live: _evidence/([A-Za-z0-9._-]+) L(\d+)(?:-L(\d+))?$")

CREDENTIAL_PATTERNS: Tuple[Tuple[str, re.Pattern[str]], ...] = (
    ("bearer-token", re.compile(r"Bearer\s+[A-Za-z0-9._~+/=-]{16,}")),
    ("jwt-token", re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b")),
    ("cookie-header", re.compile(r"(?i)\b(?:Set-Cookie|Cookie)\s*:\s*[^\s;\"'`]{8,}")),
    (
        "secret-json-field",
        re.compile(
            r'"(?:uo-idle-token|idToken|password|access_token|refresh_token|client_secret)"'
            r'\s*:\s*"(?!<REDACTED>|REDACTED)[^"\s]{6,}"'
        ),
    ),
)
EMAIL_RE = re.compile(r"\b[A-Za-z0-9._%+-]+@(?!example\.com\b)[A-Za-z0-9.-]+\.[A-Za-z]{2,}\b")

INDEX_NAME = "INDEX.md"
GENERATOR_LINE = (
    "Generated by `python3 mechanics/tools/kb.py build`; `kb.py check` fails "
    "when this file is stale. Do not edit by hand."
)

Err = Tuple[str, str]  # (code, message)


def norm_eol(text: str) -> str:
    return text.replace("\r\n", "\n")


def _is_int(v: Any) -> bool:
    return isinstance(v, int) and not isinstance(v, bool)


def _is_str_list(v: Any) -> bool:
    return isinstance(v, list) and all(isinstance(x, str) for x in v)


def raw_sha256(text: str) -> str:
    return hashlib.sha256(norm_eol(text).encode("utf-8")).hexdigest()


