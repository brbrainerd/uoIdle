def load_pages(root: Path) -> List[Dict[str, Any]]:
    pages: List[Dict[str, Any]] = []
    for kind in PAGE_DIRS:
        d = root / kind
        if not d.is_dir():
            continue
        for path in sorted(d.glob("*.md")):
            text = path.read_text(encoding="utf-8")
            fm, body, errors = parse_frontmatter(text, path.stem, root)
            pages.append(
                {
                    "kind": kind,
                    "path": path,
                    "rel": "%s/%s" % (kind, path.name),
                    "stem": path.stem,
                    "fm": fm,
                    "body": body,
                    "errors": errors,
                }
            )
    return pages


def _cell(value: Any) -> str:
    if isinstance(value, list):
        value = ", ".join(str(v) for v in value)
    return ("" if value is None else str(value)).replace("|", "\\|")


def render_index(pages: List[Dict[str, Any]]) -> str:
    counts = {t: 0 for t in TAGS}
    dir_counts = {d: 0 for d in PAGE_DIRS}
    for p in pages:
        st = p["fm"].get("status")
        if st in counts:
            counts[st] += 1
        if p["kind"] in dir_counts:
            dir_counts[p["kind"]] += 1
    dir_summary = ", ".join("%s %d" % (d, dir_counts[d]) for d in PAGE_DIRS)
    status_order = ("verified", "bundle-stated", "doc-stated", "modernuo-stated", "unverified", "contradicted")
    status_summary = ", ".join("%s %d" % (t, counts[t]) for t in status_order)
    out = [
        "# Mechanics KB index",
        "",
        GENERATOR_LINE,
        "",
        "Pages: %d (%s). Status: %s." % (len(pages), dir_summary, status_summary),
    ]
    for cat in CATEGORIES:
        rows = [p for p in pages if p["fm"].get("category") == cat]
        if not rows:
            continue
        out += ["", "## " + cat, "", "| id | title | status | aliases | file |", "|---|---|---|---|---|"]
        for p in sorted(rows, key=lambda p: (str(p["fm"].get("id", "")), p["rel"])):
            fm = p["fm"]
            out.append(
                "| [%s](%s) | %s | %s | %s | %s |"
                % (
                    _cell(fm.get("id")),
                    p["rel"],
                    _cell(fm.get("title")),
                    _cell(fm.get("status")),
                    _cell(fm.get("aliases")),
                    _cell(p["rel"]),
                )
            )
    return "\n".join(out) + "\n"


def cmd_build(root: Path) -> Dict[str, Any]:
    if not root.is_dir():
        return {"ok": False, "error": "root %s is not a directory" % root}
    pages = load_pages(root)
    with open(root / INDEX_NAME, "w", encoding="utf-8", newline="\n") as f:
        f.write(render_index(pages))
    return {"ok": True, "pages": len(pages), "wrote": INDEX_NAME}


def cmd_check(root: Path) -> Dict[str, Any]:
    errors: List[Dict[str, str]] = []

    def add(file: str, errs: List[Err]) -> None:
        errors.extend({"file": file, "code": c, "msg": m} for c, m in errs)

    if not root.is_dir():
        return {
            "ok": False,
            "pages": 0,
            "errors": [{"file": str(root), "code": "root-missing", "msg": "KB root is not a directory"}],
        }
    pages = load_pages(root)
    for p in pages:
        add(p["rel"], p["errors"])
        add(p["rel"], check_links(p["body"], root, p["path"].parent))
        add(p["rel"], check_claims(p["body"], page_raw(root, p["fm"])))
        add(p["rel"], check_cites(p["kind"], p["fm"], p["body"]))
        add(p["rel"], check_live(p["fm"], root))
        add(p["rel"], check_status(p["fm"], p["body"]))
        add(p["rel"], check_summary(p["body"]))

    index_path = root / INDEX_NAME
    actual = norm_eol(index_path.read_text(encoding="utf-8")) if index_path.is_file() else None
    if actual != render_index(pages):
        add(INDEX_NAME, [("index-stale", "INDEX.md is missing or differs from `kb.py build` output")])

    if (root / RAW_DIR / MANIFEST_NAME).is_file():
        for file, errs in check_raw_manifest(root):
            add(file, errs)

    for file, errs in check_credentials(root):
        add(file, errs)

    return {"ok": not errors, "pages": len(pages), "errors": errors}


