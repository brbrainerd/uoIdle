def run_cases() -> List[str]:
    failed: List[str] = []
    for name, case in CASES:
        try:
            case()
        except (CaseFailed, OSError, KeyError, ValueError, TypeError) as exc:
            failed.append("%s: %s" % (name, exc))
    return failed


def _run_mutations() -> Dict[str, Any]:
    missed: List[str] = []
    caught = 0
    n_codes = len({code for code, _ in MUTATIONS})
    if len(MUTATIONS) != EXPECTED_MUTATIONS or n_codes != EXPECTED_MUTATIONS:
        missed.append(
            "table: %d mutations over %d codes, expected %d distinct"
            % (len(MUTATIONS), n_codes, EXPECTED_MUTATIONS)
        )

    with tempfile.TemporaryDirectory(prefix="kb_selftest_") as tmp:
        base = Path(tmp) / "base"
        base.mkdir()
        try:
            _write_valid_kb(base)
        except (OSError, CaseFailed, ValueError) as exc:
            missed.append("baseline: cannot build valid KB (%s)" % exc)
            return {"ok": False, "mutations": len(MUTATIONS), "caught": 0, "missed": missed}

        baseline = cmd_check(base)
        if not baseline["ok"]:
            missed.append("baseline: %s" % ",".join(e["code"] for e in baseline["errors"]))

        for i, (code, mutate) in enumerate(MUTATIONS):
            root = Path(tmp) / ("m%02d" % i)
            shutil.copytree(str(base), str(root))
            try:
                mutate(root)
            except (ValueError, OSError, KeyError) as exc:
                missed.append("%s: %s" % (code, exc))
                continue
            codes = {e["code"] for e in cmd_check(root)["errors"]}
            if code in codes:
                caught += 1
            else:
                missed.append(code)

    return {"ok": not missed, "mutations": len(MUTATIONS), "caught": caught, "missed": missed}


def run_self_test() -> Dict[str, Any]:
    result = _run_mutations()
    failed = run_cases()
    result.update(cases=len(CASES), failedCases=failed, ok=result["ok"] and not failed)
    return result


