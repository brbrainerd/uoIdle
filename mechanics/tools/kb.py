def _sub(rel: str, old: str, new: str) -> Callable[[Path], None]:
    """A mutation that replaces the first `old` in `rel`; raises if absent so a
    mutation that silently does nothing is reported, not passed."""
    def mutate(root: Path) -> None:
        path = root / rel
        text = path.read_text(encoding="utf-8")
        if old not in text:
            raise ValueError("mutation target %r not in %s" % (old, rel))
        _write(path, text.replace(old, new, 1))
    return mutate


def _edit_manifest(edit: Callable[[Dict[str, Any]], None]) -> Callable[[Path], None]:
    def mutate(root: Path) -> None:
        path = root / RAW_DIR / MANIFEST_NAME
        m = json.loads(path.read_text(encoding="utf-8"))
        edit(m)
        _write(path, json.dumps(m, indent=2) + "\n")
    return mutate


