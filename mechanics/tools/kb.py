def empty_manifest(now: Optional[str] = None) -> Dict[str, Any]:
    if now is None:
        now = datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")
    return {
        "version": 1,
        "updatedAt": now,
        "bundleVersion": "0.99.0",
        "modernuoCommit": "b0e6b17c5cba3a6944ca25a9676dcdec0022ac38",
        "entries": {},
    }


def _valid_raw_rel(rel: Any) -> bool:
    if not isinstance(rel, str) or ".." in rel or "\\" in rel or rel.startswith("/"):
        return False
    parts = rel.split("/")
    if len(parts) != 2:
        return False
    sub, name = parts
    return sub in RAW_SUBDIRS and bool(RAW_FILENAME_RE.match(name))


def validate_manifest(obj: Any) -> List[str]:
    errs: List[str] = []
    if not isinstance(obj, dict):
        return ["manifest is not an object"]
    if obj.get("version") != 1:
        errs.append("version must be 1")
    if "updatedAt" in obj and not isinstance(obj.get("updatedAt"), str):
        errs.append("updatedAt must be a string")
    if "bundleVersion" in obj and not isinstance(obj.get("bundleVersion"), str):
        errs.append("bundleVersion must be a string")
    if "modernuoCommit" in obj and not isinstance(obj.get("modernuoCommit"), str):
        errs.append("modernuoCommit must be a string")

    entries = obj.get("entries")
    if not isinstance(entries, dict):
        errs.append("entries must be an object")
        return errs

    for rel, e in entries.items():
        if not _valid_raw_rel(rel):
            errs.append("entries: invalid relative path %r (must be <bundle|api|wiki|modernuo>/<filename>)" % rel)
        if not isinstance(e, dict):
            errs.append("entries[%r] must be an object" % rel)
            continue
        sha = e.get("sha256")
        if not (isinstance(sha, str) and HEX64.match(sha)):
            errs.append("entries[%r].sha256 must be 64 lower-case hex" % rel)
        lines = e.get("lines")
        if not (_is_int(lines) and lines >= 1):
            errs.append("entries[%r].lines must be a positive int" % rel)
        cat = e.get("category")
        if cat not in CATEGORIES:
            errs.append("entries[%r].category %r not in CATEGORIES" % (rel, cat))
        src = e.get("source")
        if not (isinstance(src, str) and bool(src.strip())):
            errs.append("entries[%r].source must be a non-empty string" % rel)
        if "requiredPage" in e and e["requiredPage"] is not None:
            rp = e["requiredPage"]
            if not (isinstance(rp, str) and bool(rp.strip()) and ".." not in rp and not rp.startswith("/")):
                errs.append("entries[%r].requiredPage must be a safe relative path" % rel)
    return errs


def check_raw_manifest(root: Path) -> List[Tuple[str, List[Err]]]:
    """Validate mechanics/_raw/manifest.json against _raw/{bundle,api,wiki,modernuo}/ on disk."""
    raw_dir = root / RAW_DIR
    manifest_rel = RAW_DIR + "/" + MANIFEST_NAME
    manifest_path = raw_dir / MANIFEST_NAME
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        return [(manifest_rel, [("manifest-invalid", "unreadable: %s" % exc)])]

    problems = validate_manifest(manifest)
    if problems:
        return [(manifest_rel, [("manifest-invalid", "; ".join(problems[:5]))])]

    entries: Dict[str, Dict[str, Any]] = manifest["entries"]
    out: List[Tuple[str, List[Err]]] = []

    for rel in sorted(entries):
        entry = entries[rel]
        raw_path = resolve_inside(raw_dir, rel)
        if raw_path is None:
            out.append((RAW_DIR + "/" + rel, [("raw-missing", "manifest entry %r is missing on disk" % rel)]))
        else:
            text = norm_eol(raw_path.read_text(encoding="utf-8", errors="replace"))
            actual_sha = raw_sha256(text)
            valid_line_counts = (len(text.splitlines()), len(text.split("\n")))
            if actual_sha != entry["sha256"] or entry["lines"] not in valid_line_counts:
                out.append(
                    (
                        RAW_DIR + "/" + rel,
                        [
                            (
                                "raw-hash-mismatch",
                                "entry %r sha256/lines (%s, %s) != disk (%s, %s)"
                                % (rel, entry["sha256"][:12], entry["lines"], actual_sha[:12], valid_line_counts[0]),
                            )
                        ],
                    )
                )
        req_page = entry.get("requiredPage")
        if req_page and resolve_inside(root, req_page) is None:
            out.append((req_page, [("page-missing", "manifest entry %r has no page %r" % (rel, req_page))]))

    for sub in RAW_SUBDIRS:
        sub_dir = raw_dir / sub
        if not sub_dir.is_dir():
            continue
        for p in sorted(sub_dir.rglob("*")):
            if not p.is_file() or p.name.startswith("."):
                continue
            rel = str(p.relative_to(raw_dir)).replace("\\", "/")
            if rel not in entries:
                out.append((RAW_DIR + "/" + rel, [("raw-orphan", "raw file %r has no manifest entry" % rel)]))

    return out


def check_credentials(root: Path) -> List[Tuple[str, List[Err]]]:
    """Scan _raw/, _evidence/, and page dirs for leaked tokens, cookies, passwords, or emails."""
    out: List[Tuple[str, List[Err]]] = []
    scan_dirs = [root / RAW_DIR, root / "_evidence"] + [root / d for d in PAGE_DIRS]
    for base in scan_dirs:
        if not base.is_dir():
            continue
        for path in sorted(base.rglob("*")):
            if not path.is_file() or path.suffix not in (".js", ".json", ".md", ".txt", ".cs", ".css"):
                continue
            rel = str(path.relative_to(root)).replace("\\", "/")
            text = norm_eol(path.read_text(encoding="utf-8", errors="replace"))
            file_errs: List[Err] = []
            for label, pat in CREDENTIAL_PATTERNS:
                if pat.search(text):
                    file_errs.append(("credential-leak", "%s matched in %s" % (label, rel)))
            if not rel.startswith("_raw/bundle/") and not rel.startswith("_raw/modernuo/"):
                if EMAIL_RE.search(text):
                    file_errs.append(("credential-leak", "email address matched in %s" % rel))
            if file_errs:
                out.append((rel, file_errs))
    return out


