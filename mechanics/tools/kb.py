def parse_frontmatter(
    text: str, stem: Optional[str] = None, root: Optional[Path] = None
) -> Tuple[Dict[str, Any], str, List[Err]]:
    """Return (frontmatter, body, errors). `stem` enables fm-id-mismatch and
    `root` enables fm-missing-source; both are skipped when None."""
    errors: List[Err] = []
    lines = norm_eol(text).split("\n")
    if not lines or lines[0] != "---":
        return {}, norm_eol(text), [("fm-missing", "first line is not ---")]
    try:
        close = lines.index("---", 1)
    except ValueError:
        return {}, norm_eol(text), [("fm-missing", "no closing --- line")]

    fm: Dict[str, Any] = {}
    for n, line in enumerate(lines[1:close], start=2):
        m = FM_LINE.match(line)
        if not m:
            errors.append(("fm-bad-json", "line %d is not `key: <json>`: %r" % (n, line)))
            continue
        key, raw = m.group(1), m.group(2)
        if key in fm:
            errors.append(("fm-duplicate-key", "key %r repeated on line %d" % (key, n)))
            continue
        if key not in FM_KEYS:
            errors.append(("fm-unknown-key", "unknown key %r on line %d" % (key, n)))
            continue
        try:
            fm[key] = json.loads(raw)
        except ValueError as exc:
            errors.append(("fm-bad-json", "key %r: %s" % (key, exc)))
            fm[key] = None
    body = "\n".join(lines[close + 1:])

    for key in FM_KEYS:
        if key not in fm:
            errors.append(("fm-missing-key", "missing key %r" % key))
    for key, val in fm.items():
        if val is None:
            continue  # already reported as fm-bad-json
        if key in LIST_KEYS:
            if not (isinstance(val, list) and all(isinstance(v, str) for v in val)):
                errors.append(("fm-bad-type", "%r must be a list of strings" % key))
        elif not isinstance(val, str):
            errors.append(("fm-bad-type", "%r must be a string" % key))

    def text_val(key: str) -> Optional[str]:
        v = fm.get(key)
        return v if isinstance(v, str) else None

    status = text_val("status")
    if status is not None and status not in TAGS:
        errors.append(("fm-bad-status", "status %r not in %s" % (status, "|".join(TAGS))))
    category = text_val("category")
    if category is not None and category not in CATEGORIES:
        errors.append(
            ("fm-bad-category", "category %r is not one of the fixed twelve: %s" % (category, "|".join(CATEGORIES)))
        )
    updated = text_val("updated")
    if updated is not None and not DATE_RE.match(updated):
        errors.append(("fm-bad-date", "updated %r is not YYYY-MM-DD" % updated))
    page_id = text_val("id")
    if stem is not None and page_id is not None and page_id != stem:
        errors.append(("fm-id-mismatch", "id %r != file stem %r" % (page_id, stem)))
    sources = fm.get("sources")
    if root is not None and isinstance(sources, list):
        for src in sources:
            if isinstance(src, str) and resolve_inside(root, src) is None:
                errors.append(("fm-missing-source", "source %r does not exist under the KB root" % src))
    return fm, body, errors


def resolve_inside(root: Path, rel: str) -> Optional[Path]:
    """The existing file `rel` names under `root`, or None (missing or escaping)."""
    if not rel or "\\" in rel:
        return None
    base = root.resolve()
    p = (base / rel).resolve()
    if p != base and base not in p.parents:
        return None
    return p if p.is_file() else None


