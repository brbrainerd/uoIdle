def check_links(body: str, root: Path, page_dir: Path) -> List[Err]:
    errors: List[Err] = []
    for m in WIKI_LINK.finditer(body):
        target = m.group(1)
        if not SLUG_RE.match(target) or not any((root / d / (target + ".md")).is_file() for d in PAGE_DIRS):
            errors.append(
                ("link-broken", "[[%s]] does not resolve to any page in %s" % (target, "|".join(PAGE_DIRS)))
            )
    for m in CLAIM_REF.finditer(body):
        target, cid = m.group(1), m.group(2)
        page = next(
            (
                root / d / (target + ".md")
                for d in PAGE_DIRS
                if SLUG_RE.match(target) and (root / d / (target + ".md")).is_file()
            ),
            None,
        )
        if page is None:
            continue  # link-broken already says so
        if not any(ln.startswith("- **C%s** " % cid) for ln in norm_eol(page.read_text(encoding="utf-8")).split("\n")):
            errors.append(("link-claim-missing", "[[%s]] C%s: that page has no claim C%s" % (target, cid, cid)))
    for m in MD_LINK.finditer(body):
        target = m.group(1).split("#", 1)[0]
        if not target or "://" in target or target.startswith("mailto:"):
            continue
        if not (page_dir / target).exists():
            errors.append(("link-broken", "relative link %r does not exist" % m.group(1)))
    return errors


def ws(s: str) -> str:
    """Collapse every whitespace run (raw line breaks included) to one space."""
    return " ".join(s.split())


def check_claims(body: str, raw_text: Optional[str]) -> List[Err]:
    """Every `- **C` line must be a well-formed claim with a known tag whose
    quote is verbatim (modulo whitespace) inside its cited raw lines.
    `raw_text` is sources[0]; None skips the quote checks (that page already
    has fm-missing-source)."""
    errors: List[Err] = []
    raw_lines = norm_eol(raw_text).split("\n") if raw_text is not None else []
    raw_ws = ws(norm_eol(raw_text)) if raw_text is not None else ""
    for line in body.split("\n"):
        if not line.startswith(CLAIM_PREFIX):
            continue
        m = CLAIM_LINE.match(line)
        if not m or not ws(m.group(3)):
            errors.append(("claim-malformed", "not a claim line: %r" % line[:120]))
            continue
        cid, tag, quote = m.group(1), m.group(2), ws(m.group(3))
        if tag not in TAGS:
            errors.append(("claim-unknown-tag", "C%s tag %r not in %s" % (cid, tag, "|".join(TAGS))))
        if raw_text is None or m.group(6) is not None:
            continue  # an (evidence N) claim quotes no raw; check_cites owns it
        a = int(m.group(4))
        b = int(m.group(5) or a)
        if quote not in raw_ws:
            errors.append(("quote-not-in-raw", "C%s quote is not verbatim in the raw file" % cid))
        elif a < 1 or b < a or quote not in ws("\n".join(raw_lines[a - 1:b])):
            errors.append(("quote-line-mismatch", "C%s quote is in raw but not at L%d-L%d" % (cid, a, b)))
    return errors


def check_cites(kind: str, fm: Dict[str, Any], body: str) -> List[Err]:
    """What a claim may cite. `(evidence N)` is for topics pages only, never
    uses raw-only tags (bundle-stated, doc-stated, modernuo-stated), names an
    existing `evidence` entry with one of EVIDENCE_PREFIXES, and a verified or
    contradicted one must name a MEASURED_PREFIXES entry.
    A `(raw ...)` cite needs a `sources[0]` to quote."""
    errors: List[Err] = []
    evidence = fm.get("evidence") if _is_str_list(fm.get("evidence")) else []
    sources = fm.get("sources") if isinstance(fm.get("sources"), list) else []
    for line in body.split("\n"):
        m = CLAIM_LINE.match(line)
        if not m:
            continue
        cid, tag = m.group(1), m.group(2)
        if m.group(6) is None:
            if not sources:
                errors.append(("claim-bad-cite", "C%s cites raw lines but the page has no sources" % cid))
            continue
        n = int(m.group(6))
        entry = evidence[n - 1] if 1 <= n <= len(evidence) else None
        why = None
        if kind != "topics":
            why = "an (evidence N) claim belongs on a topics page"
        elif tag in RAW_ONLY_TAGS:
            why = "an (evidence N) claim cannot be %s; quote the raw instead" % tag
        elif entry is None:
            why = "evidence %d is not one of the page's %d entries" % (n, len(evidence))
        elif not entry.startswith(EVIDENCE_PREFIXES):
            why = "evidence %d lacks an allowed prefix (%s)" % (n, "/".join(p.strip() for p in EVIDENCE_PREFIXES))
        elif tag in ("verified", "contradicted") and not entry.startswith(MEASURED_PREFIXES):
            why = "a %s claim must cite a measured entry (%s), not %r" % (
                tag,
                "/".join(p.strip() for p in MEASURED_PREFIXES),
                entry.split(":", 1)[0],
            )
        if why:
            errors.append(("claim-bad-cite", "C%s: %s" % (cid, why)))
    return errors


def check_live(fm: Dict[str, Any], root: Path) -> List[Err]:
    """Every `live:` evidence entry names an existing `_evidence/` file and an in-range line span."""
    errors: List[Err] = []
    for entry in fm.get("evidence") if _is_str_list(fm.get("evidence")) else []:
        if not entry.startswith("live: "):
            continue
        m = LIVE_CITE.match(entry)
        path = resolve_inside(root / "_evidence", m.group(1)) if m else None
        if not m or path is None:
            errors.append(("live-bad-cite", "%r is not `live: _evidence/<existing file> L<a>[-L<b>]`" % entry))
            continue
        a = int(m.group(2))
        b = int(m.group(3) or a)
        n = len(norm_eol(path.read_text(encoding="utf-8")).split("\n"))
        if a < 1 or b < a or b > n:
            errors.append(("live-bad-cite", "%r: lines outside 1-%d" % (entry, n)))
    return errors


def claim_tags(body: str) -> List[str]:
    tags = []
    for line in body.split("\n"):
        m = CLAIM_LINE.match(line)
        if m and m.group(2) in TAGS:
            tags.append(m.group(2))
    return tags


def _default_status_for_sources(fm: Dict[str, Any]) -> str:
    sources = fm.get("sources")
    if isinstance(sources, list) and sources and isinstance(sources[0], str):
        s0 = sources[0]
        if s0.startswith("_raw/modernuo/"):
            return "modernuo-stated"
        if s0.startswith("_raw/wiki/"):
            return "doc-stated"
    return "bundle-stated"


def check_status(fm: Dict[str, Any], body: str) -> List[Err]:
    """Page status is its weakest claim, or source-derived default when claims is empty."""
    status = fm.get("status")
    if status not in TAGS:
        return []  # fm-bad-status already says so
    tags = claim_tags(body)
    expected = min(tags, key=lambda t: RANK[t]) if tags else _default_status_for_sources(fm)
    if status != expected:
        return [("status-mismatch", "status %r but weakest claim is %r" % (status, expected))]
    return []


def check_summary(body: str) -> List[Err]:
    """Numbers live only in verbatim claims, never in Summary prose."""
    inside = False
    for line in body.split("\n"):
        if line.startswith("## "):
            inside = line.strip() == "## Summary"
        elif inside and re.search(r"\d", line):
            return [("summary-number", "digit in Summary: %r" % line[:120])]
    return []


def page_raw(root: Path, fm: Dict[str, Any]) -> Optional[str]:
    sources = fm.get("sources")
    if not (isinstance(sources, list) and sources and isinstance(sources[0], str)):
        return None
    path = resolve_inside(root, sources[0])
    return norm_eol(path.read_text(encoding="utf-8")) if path else None


