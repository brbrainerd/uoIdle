def main(argv: Optional[List[str]] = None) -> int:
    default_root = Path(__file__).resolve().parent.parent
    ap = argparse.ArgumentParser(description=__doc__.split("\n", 1)[0])
    ap.add_argument("--self-test", action="store_true", help="run the self-contained mutation self-test")
    sub = ap.add_subparsers(dest="cmd")
    for name in ("build", "check"):
        sp = sub.add_parser(name)
        sp.add_argument("--root", type=Path, default=default_root, help="KB root (default: %(default)s)")
    args = ap.parse_args(argv)

    if args.self_test:
        result = run_self_test()
    elif args.cmd == "build":
        result = cmd_build(args.root)
    elif args.cmd == "check":
        result = cmd_check(args.root)
    else:
        ap.print_usage(sys.stderr)
        result = {"ok": False, "error": "choose build, check or --self-test"}
    print(json.dumps(result))
    return 0 if result.get("ok") else 1


